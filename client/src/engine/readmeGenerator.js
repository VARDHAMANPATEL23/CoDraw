export function generateReadme(meta) {
  const projectName = meta.name || 'My CoDraw App';
  const projectFolder = projectName.toLowerCase().replace(/[^a-z0-9]/g, '-');
  const stylingSystem = meta.stylingSystem || 'tailwind';
  const language = meta.language === 'ts' ? 'TypeScript' : 'JavaScript';

  let stylingInstructions = '';
  if (stylingSystem === 'tailwind') {
    stylingInstructions = 'Tailwind CSS is configured in `tailwind.config.js` and imported in `src/index.css`. You can add standard Tailwind utility classes directly to JSX.';
  } else if (stylingSystem === 'css-modules') {
    stylingInstructions = 'CSS Modules are placed alongside each component in `src/components/*.module.css`. Classes are scoped locally.';
  } else if (stylingSystem === 'bootstrap') {
    stylingInstructions = 'Bootstrap 5 styles are imported via `src/index.css`. Use standard Bootstrap classes like `btn`, `navbar`, and `card`.';
  }

  let languageNote = language === 'TypeScript'
    ? 'This project uses TypeScript with strict typing. Component props are typed with interfaces.'
    : 'This project uses standard JavaScript (React JSX).';

  const readmeContent = `# ${projectName}

Generated by CoDraw — https://codraw.app

## Prerequisites
- Node.js v18 or higher
- npm v9 or higher

## Getting Started

\`\`\`bash
# 1. Unzip the project
unzip ${projectFolder}.zip && cd ${projectFolder}

# 2. Install dependencies
npm install

# 3. Start the development server
npm start
\`\`\`

The app runs at http://localhost:3000

## Project Structure

\`\`\`
src/
├── components/     # Individual UI components
├── pages/
│   └── Home.jsx    # Main page — edit this to rearrange sections
├── App.js          # Root component
└── index.js        # Entry point
\`\`\`

## Styling System: ${stylingSystem}

${stylingInstructions}

## How to Customise

- **Change text:** Open the component file in \`src/components/\` and edit the prop defaults or the JSX directly.
- **Add a new section:** Import a component into \`src/pages/Home.jsx\` and add it to the JSX.
- **Change colours:** Edit the \`style\` prop or className on the relevant component.

## Common Errors

| Error | Fix |
|---|---|
| \`npm install\` fails | Make sure Node.js v18+ is installed: \`node -v\` |
| Port 3000 in use | Run \`PORT=3001 npm start\` |
| Tailwind classes not applying | Ensure \`tailwind.config.js\` \`content\` paths include \`./src/**/*.{js,jsx}\` |
| Module not found | Delete \`node_modules/\` and run \`npm install\` again |

## Language: ${language}

${languageNote}
`;

  return {
    filename: 'README.md',
    content: readmeContent.trim(),
  };
}
